export type Language = "system" | "en" | "zh";

/** Resolve the active table for a resolved language ("en" | "zh"). */
export function tableFor(lang: "en" | "zh"): LocalizedTable {
  return lang === "zh" ? ZH : EN;
}

/** Translate with printf-style interpolation; falls back to the key itself. */
export function makeT(lang: "en" | "zh") {
  const table = tableFor(lang);
  return function t(key: string, ...args: Array<string | number>): string {
    const s = table[key as MsgKey] ?? EN[key as MsgKey] ?? key;
    return s.replace(/\{(\d+)\}/g, (_m, i) => String(args[Number(i)] ?? ""));
  };
}
